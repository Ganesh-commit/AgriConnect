/**
 * Translates a crop title into Telugu when `lang === 'te'`.
 */
export function translateCropName(name, lang = 'en') {
  if (!name || lang !== 'te') return name || '';
  const trimmed = String(name).trim();
  if (CROP_NAME_TE[trimmed]) return CROP_NAME_TE[trimmed];

  // Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [enKey, teVal] of Object.entries(CROP_NAME_TE)) {
    if (enKey.toLowerCase() === lower) return teVal;
  }

  // Word-by-word fallback for custom farmer crop titles
  const words = trimmed.split(/\s+/);
  let translatedAny = false;
  const mappedWords = words.map((w) => {
    const clean = w.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (WORD_MAP_TE[clean]) {
      translatedAny = true;
      return WORD_MAP_TE[clean];
    }
    return w;
  });

  return translatedAny ? mappedWords.join(' ') : trimmed;
}

/**
 * Translates a crop description into fluent Telugu when `lang === 'te'`.
 */
export function translateCropDescription(description, cropName = '', category = '', lang = 'en') {
  if (!description || lang !== 'te') return description || '';
  const text = String(description).trim();

  // If already contains Telugu characters, return as-is
  if (/[\u0C00-\u0C7F]/.test(text)) return text;

  const teCropName = translateCropName(cropName, 'te') || 'తాజా పంట';
  const teMethod =
    CATEGORY_METHODS_TE[category] ||
    'సహజ వ్యవసాయ పద్ధతులు మరియు నాణ్యమైన సంరక్షణతో';

  // Match seeded description pattern ("I offer fresh <name>, raised or prepared with...")
  if (/^I offer fresh /i.test(text) || /preserve the character of this local variety/i.test(text)) {
    return `మా పొలం నుండి నేరుగా తాజా ${teCropName} అందిస్తున్నాము. ఇది ${teMethod} పండించబడింది. ఈ ప్రాంతీయ రకం సహజ రుచి మరియు నాణ్యత చెక్కుచెదరకుండా సరైన దశలో కోసి, మీ మార్కెట్‌కు తాజాగా అందించబడుతుంది.`;
  }

  return `రైతు పొలం నుండి నేరుగా సేకరించిన నాణ్యమైన ${teCropName}. ${teMethod} సాగు చేయబడి, తాజాగా అమ్మకానికి సిద్ధంగా ఉంది.`;
}

/**
 * Translates measurement unit (kg, quintal, piece, etc.) when `lang === 'te'`.
 */
export function translateUnit(unit, lang = 'en') {
  if (!unit || lang !== 'te') return unit || '';
  return UNIT_TE[String(unit).toLowerCase()] || unit;
}

/**
 * Translates village/district/state strings into Telugu when `lang === 'te'`.
 */
export function translateLocationText(locStr, lang = 'en') {
  if (!locStr || lang !== 'te') return locStr || '';
  return String(locStr)
    .split(',')
    .map((part) => {
      const p = part.trim();
      return LOCATION_TE[p] || p;
    })
    .join(', ');
}

